"""
NepaliLang Standard Library - Ganit (Math)
Provides mathematical functions.
"""

def jod(a, b):
    """Add two numbers."""
    return a + b

def ghata(a, b):
    """Subtract two numbers."""
    return a - b

def guna(a, b):
    """Multiply two numbers."""
    return a * b

def bhag(a, b):
    """Divide two numbers."""
    return a / b

def sqrt(x):
    """Square root."""
    return x ** 0.5

def power(x, y):
    """Power function."""
    return x ** y